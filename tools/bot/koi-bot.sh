#!/usr/bin/env bash
# Koi Lichess bot control (macOS).
#
#   koi-bot.sh install [--token TOKEN]   clone/refresh lichess-bot, make the
#                                        venv, install the engine, write config
#   koi-bot.sh start | stop | restart    run or stop the bot
#   koi-bot.sh status                    version, pid state, recent log
#   koi-bot.sh update [--force]          install the newest Koi release and
#                                        restart the bot when it changed
#   koi-bot.sh logs [N]                  tail the bot log
#   koi-bot.sh install-launchd           start at login, restart on crash,
#                                        check for a new release every hour, and
#                                        autostart only when the Mac is idle
#   koi-bot.sh autostart                 start when idle/light, pause under
#                                        heavy load unless a game is in progress
#   koi-bot.sh uninstall-launchd         remove those agents
#
# The lichess-bot bridge itself is https://github.com/lichess-bot-devs/lichess-bot
# (AGPLv3); this script only wires a Koi build into it.
set -euo pipefail

BOT_HOME="${KOI_BOT_HOME:-$HOME/koi-bot}"
UPSTREAM="https://github.com/lichess-bot-devs/lichess-bot.git"
REPO="nhatquang1701/Koi-engine"
ENGINE_DIR="$BOT_HOME/engines"
ENGINE="$ENGINE_DIR/koi-engine"
NET="$ENGINE_DIR/koi.nnue"
CONFIG="$BOT_HOME/config.yml"
TOKEN_FILE="$BOT_HOME/token"
PID_FILE="$BOT_HOME/bot.pid"
LOG_DIR="$BOT_HOME/logs"
BOT_LOG="$LOG_DIR/bot.log"
UPDATE_LOG="$LOG_DIR/update.log"
VERSION_FILE="$ENGINE_DIR/VERSION"
CLONE="$BOT_HOME/lichess-bot"
LABEL="org.koi.lichess-bot"
PLIST="$HOME/Library/LaunchAgents/$LABEL.plist"
UPDATE_LABEL="org.koi.lichess-bot-update"
UPDATE_PLIST="$HOME/Library/LaunchAgents/$UPDATE_LABEL.plist"
AUTOSTART_LABEL="org.koi.lichess-bot-autostart"
AUTOSTART_PLIST="$HOME/Library/LaunchAgents/$AUTOSTART_LABEL.plist"
AUTOSTART_LOG="$LOG_DIR/autostart.log"
THREADS="${KOI_BOT_THREADS:-4}"
HASH_MB="${KOI_BOT_HASH:-512}"
PYTHON_PIN_FILE="$BOT_HOME/python-bin"
WORK_TMP=""
cleanup() { [ -n "$WORK_TMP" ] && rm -rf "$WORK_TMP"; }
trap cleanup EXIT

# lichess-bot requires Python 3.11+.  Resolve the interpreter once, remember it
# so a venv rebuild keeps using it, and override with KOI_BOT_PYTHON.
bot_python() {
    if [ -f "$PYTHON_PIN_FILE" ]; then
        tr -d '[:space:]' < "$PYTHON_PIN_FILE"
    elif [ -n "${KOI_BOT_PYTHON:-}" ]; then
        printf '%s' "$KOI_BOT_PYTHON"
    else
        printf '%s' "python3"
    fi
}

log() { printf '%s %s\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$*"; }
die() { log "error: $*" >&2; exit 1; }

ensure_dirs() {
    mkdir -p "$BOT_HOME" "$ENGINE_DIR" "$LOG_DIR"
}

latest_tag() {
    curl -fsSL -H 'Accept: application/vnd.github+json' \
        "https://api.github.com/repos/$REPO/releases/latest" |
        python3 -c 'import json,sys; print(json.load(sys.stdin)["tag_name"])'
}

asset_url() {
    local pattern="$1" json="$2"
    printf '%s' "$json" | PATTERN="$pattern" python3 -c '
import json, os, sys
pattern = os.environ["PATTERN"]
want_sidecar = pattern.endswith(".sha256")
for asset in json.load(sys.stdin).get("assets", []):
    name = asset["name"]
    is_sidecar = name.endswith(".sha256")
    if pattern in name and is_sidecar == want_sidecar:
        print(asset["browser_download_url"])
        break
'
}

installed_version() {
    if [ -f "$VERSION_FILE" ]; then cat "$VERSION_FILE"; else echo "none"; fi
}

# True when $1 is strictly newer than $2 (version numbers, "v" tolerated).
is_newer() {
    local newest="$1" current="$2"
    [ "$newest" = "$current" ] && return 1
    [ "$current" = "none" ] && return 0
    [ "$(printf '%s\n%s\n' "$current" "$newest" | sort -V | tail -1)" = "$newest" ]
}

write_config() {
    [ -f "$TOKEN_FILE" ] || die "no token: run '$0 install --token <lichess-token>'"
    local token
    token="$(tr -d '[:space:]' < "$TOKEN_FILE")"
    [ -n "$token" ] || die "the token file is empty: $TOKEN_FILE"
    local net_option=""
    if [ -f "$NET" ]; then
        net_option="    EvalFile: \"$NET\""
    fi
    # Only advertise the newer options when the installed engine supports them:
    # lichess-bot refuses to start when the config names an option the engine
    # does not list, so probe the UCI handshake first.
    local extra_uci=""
    local engine_handshake=""
    if [ -x "$ENGINE" ]; then
        engine_handshake="$(printf 'uci\nquit\n' | "$ENGINE" 2>/dev/null || true)"
    fi
    if printf '%s' "$engine_handshake" | grep -q 'option name Contempt'; then
        extra_uci="    Contempt: 50"
        if printf '%s' "$engine_handshake" | grep -q 'option name Dynamic Overhead'; then
            extra_uci="$extra_uci
    Dynamic Overhead: true"
        fi
    fi
    umask 077
    cat > "$CONFIG" <<YAML
# Generated by tools/bot/koi-bot.sh — edits are overwritten on install/update.
token: "$token"
url: "https://lichess.org/"

engine:
  dir: "$ENGINE_DIR"
  name: "koi-engine"
  protocol: "uci"
  ponder: true
  working_dir: "$ENGINE_DIR"
  silence_stderr: false
  uci_options:
    Threads: $THREADS
    Hash: $HASH_MB
    UCI_ShowWDL: true
    # Play for wins: a draw scores -50 cp for Koi, so it only accepts a draw
    # when every alternative is worse.  Overhead follows the time control.
$extra_uci
$net_option

abort_time: 30
# 150 ms leaves room for the engine's own dynamic overhead in bullet games
# (the old 2000 ms value consumed a 1+1 increment on every move).
move_overhead: 150
quit_after_all_games_finish: true
pgn_directory: "$BOT_HOME/games"

challenge:
  concurrency: 1
  sort_by: "best"
  preference: "none"
  accept_bot: true
  only_bot: false
  max_increment: 20
  min_increment: 0
  max_base: 1800
  min_base: 0
  variants:
    - standard
  time_controls:
    # All standard Lichess time controls (1+0, 1+1, 3+2, 5+0, 10+0, ...).
    - bullet
    - blitz
    - rapid
    - classical
  modes:
    - casual
    - rated

greeting:
  hello: "Hi! I'm {me}, a Koi engine bot. Good luck!"
  goodbye: "Good game!"

matchmaking:
  allow_matchmaking: false
YAML
    chmod 600 "$CONFIG"
}

install_upstream() {
    ensure_dirs
    if [ -d "$CLONE/.git" ]; then
        git -C "$CLONE" pull --ff-only --quiet
    else
        git clone --depth 1 --quiet "$UPSTREAM" "$CLONE"
    fi
    if [ ! -d "$CLONE/.venv" ]; then
        local python version
        python="$(bot_python)"
        [ -x "$python" ] || die "python interpreter not found: $python"
        version="$("$python" -c 'import sys; print("%d.%d" % sys.version_info[:2])')"
        python3 -c 'import sys; sys.exit(0 if tuple(map(int, sys.argv[1].split("."))) >= (3, 11) else 1)' \
            "$version" || die "lichess-bot needs Python 3.11 or newer; $python is $version"
        "$python" -m venv "$CLONE/.venv"
        printf '%s' "$python" > "$PYTHON_PIN_FILE"
        log "venv created with $python ($version)"
    fi
    "$CLONE/.venv/bin/pip" install --quiet --upgrade pip
    "$CLONE/.venv/bin/pip" install --quiet -r "$CLONE/requirements.txt"
    log "lichess-bot ready at $CLONE ($(git -C "$CLONE" rev-parse --short HEAD))"
}

install_engine() {
    local json tag url sidecar tmp
    json="$(curl -fsSL -H 'Accept: application/vnd.github+json' \
        "https://api.github.com/repos/$REPO/releases/latest")"
    tag="$(printf '%s' "$json" | python3 -c 'import json,sys; print(json.load(sys.stdin)["tag_name"])')"
    url="$(asset_url "macos-arm64.tar.gz" "$json")"
    sidecar="$(asset_url "macos-arm64.tar.gz.sha256" "$json")"
    [ -n "$url" ] || die "release $tag has no macOS arm64 package"
    [ -n "$sidecar" ] || die "release $tag has no sha256 sidecar"

    if [ "$tag" = "$(installed_version)" ] && [ "${FORCE:-0}" != "1" ]; then
        log "engine already at $tag"
        return 1
    fi

    tmp="$(mktemp -d)"
    WORK_TMP="$tmp"
    curl -fsSL -o "$tmp/package.tar.gz" "$url"
    curl -fsSL -o "$tmp/package.tar.gz.sha256" "$sidecar"
    local expected actual
    expected="$(awk 'NR==1 {print $1}' "$tmp/package.tar.gz.sha256")"
    actual="$(shasum -a 256 "$tmp/package.tar.gz" | awk '{print $1}')"
    [ -n "$expected" ] && [ "$expected" = "$actual" ] ||
        die "checksum verification failed for $tag (expected $expected, got $actual)"

    tar -xzf "$tmp/package.tar.gz" -C "$ENGINE_DIR"
    chmod +x "$ENGINE_DIR"/koi-engine "$ENGINE_DIR"/koi-bench 2>/dev/null || true

    local net_url
    net_url="$(asset_url ".nnue" "$json")"
    if [ -n "$net_url" ]; then
        curl -fsSL -o "$tmp/net.nnue" "$net_url"
        mv "$tmp/net.nnue" "$NET"
    fi

    printf '%s' "$tag" > "$VERSION_FILE"
    log "installed engine $tag${net_url:+ with $(basename "$NET")}"
    return 0
}

bot_loaded() {
    launchctl print "gui/$UID/$LABEL" >/dev/null 2>&1
}

bot_pid() {
    if [ -f "$PID_FILE" ]; then
        local pid
        pid="$(cat "$PID_FILE")"
        if [ -n "$pid" ] && kill -0 "$pid" 2>/dev/null; then printf '%s' "$pid"; fi
    fi
}

run_foreground() {
    # launchd runs this path; opening the status window here survives the ssh
    # session that may have kicked the service, and the window shows immediately.
    show_status_window
    [ -f "$CONFIG" ] || die "no config: run '$0 install --token <token>' first"
    cd "$CLONE"
    exec "$CLONE/.venv/bin/python" lichess-bot.py --config "$CONFIG"
}

cmd_install() {
    local token=""
    while [ $# -gt 0 ]; do
        case "$1" in
            --token) shift; token="${1:-}" ;;
            *) die "unknown install option: $1" ;;
        esac
        shift
    done
    ensure_dirs
    if [ -n "$token" ]; then
        umask 077
        printf '%s' "$token" > "$TOKEN_FILE"
        chmod 600 "$TOKEN_FILE"
    fi
    install_upstream
    FORCE=0 install_engine || true
    write_config
    log "installed: engine $(installed_version), config $CONFIG"
    [ -f "$TOKEN_FILE" ] || log "next: put a lichess OAuth token in $TOKEN_FILE (chmod 600), then '$0 start'"
}

cmd_update() {
    FORCE=0
    while [ $# -gt 0 ]; do
        case "$1" in
            --force) FORCE=1 ;;
            *) die "unknown update option: $1" ;;
        esac
        shift
    done
    ensure_dirs
    local tag before changed=1
    before="$(installed_version)"
    tag="$(latest_tag)"
    if [ "$tag" = "$before" ] && [ "$FORCE" != "1" ]; then
        log "up to date at $tag"
        return 0
    fi
    install_engine && changed=0
    if [ "$changed" = "0" ]; then
        write_config
        if bot_loaded || [ -n "$(bot_pid)" ]; then
            log "restarting the bot on $tag"
            cmd_restart
        fi
    fi
    log "engine $(installed_version) (was $before)" >> "$UPDATE_LOG"
}

# --- Desktop status window --------------------------------------------------
# While the bot is online a Terminal window titled "LICHESS BOT RUNNING" shows
# the live state; when the bot goes offline the window prints OFFLINE and closes
# itself.  `open -a Terminal` needs no Automation permission; the generated
# .command file polls the bot process and closes the window on exit.
STATUS_WINDOW_TITLE="LICHESS BOT RUNNING"
STATUS_WINDOW_SCRIPT="$BOT_HOME/status-window.command"

write_status_window_script() {
    cat > "$STATUS_WINDOW_SCRIPT" <<'STATUS_SCRIPT'
#!/bin/bash
# Generated by koi-bot.sh: live Lichess bot status window.  Exits (and closes
# the window) when the bot process disappears.
BOT_HOME="${KOI_BOT_HOME:-$HOME/koi-bot}"
CONFIG="$BOT_HOME/config.yml"
printf '\033]0;LICHESS BOT RUNNING\007'
printf '\n\033[1;32m  LICHESS BOT RUNNING\033[0m\n\n'
printf 'engine: %s\n' "$(cat "$BOT_HOME/engines/VERSION" 2>/dev/null || echo unknown)"
printf 'config: %s\n' "$CONFIG"
printf 'log:    %s\n\n' "$BOT_HOME/logs/bot.log"
printf 'This window closes when the bot stops.\n'
while pgrep -f "lichess-bot.py --config $CONFIG" >/dev/null 2>&1; do
    sleep 5
done
printf '\n\033[1;31m  LICHESS BOT OFFLINE\033[0m\n'
sleep 2
( osascript -e 'tell application "Terminal" to close (every window whose name contains "LICHESS BOT RUNNING")' >/dev/null 2>&1 & )
sleep 1
exit 0
STATUS_SCRIPT
    chmod +x "$STATUS_WINDOW_SCRIPT"
}

show_status_window() {
    # Reuse an existing window instead of stacking duplicates.  Use pgrep, not
    # AppleScript: an Automation prompt must never block the bot lifecycle.
    if pgrep -f "$STATUS_WINDOW_SCRIPT" >/dev/null 2>&1; then
        return 0
    fi
    write_status_window_script
    log "status window: opening $STATUS_WINDOW_SCRIPT"
    if ! open -a Terminal "$STATUS_WINDOW_SCRIPT" >>"$BOT_LOG" 2>&1; then
        log "status window: open failed (the Terminal window is optional)"
    fi
}

close_status_window() {
    # Fire-and-forget: closing is cosmetic and must not delay stop/restart.
    ( osascript -e 'tell application "Terminal" to close (every window whose name contains "LICHESS BOT RUNNING")' >/dev/null 2>&1 & ) || true
}

# True while lichess-bot is inside a game: the last game-id line is newer than
# the last "Game over"/"Process Freed" marker in the recent log.
bot_is_playing() {
    [ -f "$BOT_LOG" ] || return 1
    tail -n 400 "$BOT_LOG" 2>/dev/null | awk '
        /Game over|Process Freed/ { active = 0 }
        /game [A-Za-z0-9]+/ { active = 1 }
        END { exit active ? 0 : 1 }'
}

# Idle-aware autostart: start the bot when the Mac is idle or lightly loaded;
# when heavy work starts, pause the bot only if it is not currently playing.
cmd_autostart() {
    local ncpu load1 heavy=0
    ncpu="$(sysctl -n hw.ncpu 2>/dev/null || echo 1)"
    load1="$(sysctl -n vm.loadavg 2>/dev/null | awk '{print $2}')"
    [ -n "$load1" ] || load1=0
    if pgrep -f "koi-bench|ctest|ninja|cmake --build|python.*train|elo_estimate|uci_match|net_match|release_verify|koi_search_tests|koi_strength_tests" >/dev/null 2>&1; then
        heavy=1
    fi
    if ! awk -v l="$load1" -v c="$ncpu" 'BEGIN { exit !(l < 0.6 * c) }'; then
        heavy=1
    fi
    if bot_loaded || [ -n "$(bot_processes)" ]; then
        if [ "$heavy" = "1" ]; then
            if bot_is_playing; then
                log "autostart: heavy work detected but a game is in progress; leaving the bot running"
            else
                log "autostart: heavy work detected and no game in progress; pausing the bot"
                cmd_stop
            fi
        fi
        return 0
    fi
    if [ "$heavy" = "1" ]; then
        log "autostart: heavy work in progress (load ${load1}/${ncpu}); not starting the bot"
        return 0
    fi
    log "autostart: Mac is idle or lightly loaded (load ${load1}/${ncpu}); starting the bot"
    cmd_start
}

cmd_start() {
    [ -f "$CONFIG" ] || die "no config: run '$0 install --token <token>' first"
    rotate_log_if_large
    if [ -f "$PLIST" ]; then
        # launchd owns the lifecycle once the agent exists.  Kill any instance
        # started by hand first so the bot never runs twice.
        kill_stray_bots
        launchctl bootout "gui/$UID/$LABEL" >/dev/null 2>&1 || true
        launchctl bootstrap "gui/$UID" "$PLIST" >/dev/null 2>&1 || true
        launchctl kickstart -k "gui/$UID/$LABEL" >/dev/null 2>&1 || true
        log "bot started (launchd)"
        show_status_window
        return 0
    fi
    if bot_loaded; then
        launchctl kickstart "gui/$UID/$LABEL" >/dev/null 2>&1 || true
        log "bot started (launchd)"
        show_status_window
        return 0
    fi
    if [ -n "$(bot_processes)" ]; then
        log "bot already running (pid(s) $(bot_processes | tr '\n' ' '))"
        return 0
    fi
    : > "$BOT_LOG"
    # `cd` in this shell (not a subshell) so `$!` is lichess-bot's own pid.
    cd "$CLONE" || die "missing clone: $CLONE"
    nohup "$CLONE/.venv/bin/python" lichess-bot.py --config "$CONFIG" \
        >> "$BOT_LOG" 2>&1 &
    local pid=$!
    cd "$OLDPWD" || true
    printf '%s' "$pid" > "$PID_FILE"
    sleep 2
    kill -0 "$pid" 2>/dev/null || die "the bot exited immediately; see $BOT_LOG"
    log "bot started (pid $pid, log $BOT_LOG)"
    show_status_window
}

# Every process running this bot's config, whether or not the pidfile matches.
bot_processes() {
    pgrep -f "lichess-bot.py --config $CONFIG" 2>/dev/null || true
}

# lichess-bot runs its engines through a multiprocessing pool; those workers
# survive a hard-killed parent and then spam the log with tracebacks, so any
# orphan belonging to this venv is cleaned up with the bot.
kill_orphan_workers() {
    local p
    for p in $(pgrep -f 'multiprocessing' 2>/dev/null); do
        if ps -o command= -p "$p" 2>/dev/null | grep -q "$CLONE/.venv"; then
            kill -TERM "$p" 2>/dev/null || true
        fi
    done
    sleep 1
    for p in $(pgrep -f 'multiprocessing' 2>/dev/null); do
        if ps -o command= -p "$p" 2>/dev/null | grep -q "$CLONE/.venv"; then
            kill -KILL "$p" 2>/dev/null || true
        fi
    done
}

# launchd owns the log file handle, so rotate before the next spawn, never from
# inside the running bot.
rotate_log_if_large() {
    [ -f "$BOT_LOG" ] || return 0
    local size
    size="$(wc -c < "$BOT_LOG" | tr -d ' ')"
    if [ "${size:-0}" -gt 20000000 ]; then
        mv -f "$BOT_LOG" "$BOT_LOG.1"
        : > "$BOT_LOG"
        log "rotated bot.log (${size} bytes)"
    fi
}

# Terminate bot processes started outside launchd (graceful, then hard).
kill_stray_bots() {
    local pids p
    pids="$(bot_processes)"
    kill_orphan_workers
    [ -n "$pids" ] || return 0
    for p in $pids; do kill -TERM "$p" 2>/dev/null || true; done
    for _ in $(seq 1 20); do
        [ -z "$(bot_processes)" ] && break
        sleep 1
    done
    for p in $(bot_processes); do kill -KILL "$p" 2>/dev/null || true; done
    rm -f "$PID_FILE"
}

cmd_stop() {
    close_status_window
    local pid pids p was_loaded=0
    if bot_loaded; then
        was_loaded=1
        launchctl bootout "gui/$UID/$LABEL" >/dev/null 2>&1 || true
    fi
    # Also clear anything started by hand, so "stopped" always means stopped.
    pid="$(bot_pid)"
    pids="$(bot_processes)"
    if [ -z "$pid" ] && [ -z "$pids" ]; then
        rm -f "$PID_FILE"
        if [ "$was_loaded" = "1" ]; then
            log "bot stopped (launchd)"
        else
            log "bot is not running"
        fi
        return 0
    fi
    [ -n "$pid" ] && kill -TERM "$pid" 2>/dev/null || true
    for p in $pids; do kill -TERM "$p" 2>/dev/null || true; done
    for _ in $(seq 1 30); do
        [ -z "$(bot_processes)" ] && break
        sleep 1
    done
    for p in $(bot_processes); do kill -KILL "$p" 2>/dev/null || true; done
    if [ -n "$(bot_processes)" ]; then
        log "bot processes survived the grace period: $(bot_processes | tr '\n' ' ')"
    else
        log "bot stopped${pid:+ (pid $pid)}"
    fi
    rm -f "$PID_FILE"
}

cmd_restart() {
    cmd_stop
    cmd_start
}

cmd_status() {
    printf 'engine:   %s (%s)\n' "$(installed_version)" "$ENGINE"
    if [ -f "$NET" ]; then printf 'net:      %s\n' "$NET"; else printf 'net:      missing\n'; fi
    if bot_loaded; then
        printf 'service:  launchd %s\n' "$LABEL"
        printf 'autostart: %s (idle-only, every 120 s)\n' "$AUTOSTART_LABEL"
    elif [ -n "$(bot_processes)" ]; then
        printf 'service:  running, pid(s) %s\n' "$(bot_processes | tr '\n' ' ')"
    else
        printf 'service:  stopped\n'
    fi
    printf 'window:   %s\n' "$STATUS_WINDOW_TITLE"
    if [ -f "$BOT_LOG" ]; then
        printf -- '--- last log lines ---\n'
        tail -n 5 "$BOT_LOG"
    fi
    return 0
}

cmd_logs() {
    local count="${1:-40}"
    [ -f "$BOT_LOG" ] || die "no log yet at $BOT_LOG"
    tail -n "$count" "$BOT_LOG"
}

cmd_install_launchd() {
    [ -f "$CONFIG" ] || die "run '$0 install --token <token>' first"
    mkdir -p "$HOME/Library/LaunchAgents"
    cat > "$PLIST" <<PLIST_XML
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key><string>$LABEL</string>
    <key>ProgramArguments</key>
    <array>
        <string>$BOT_HOME/koi-bot.sh</string>
        <string>run</string>
    </array>
    <key>WorkingDirectory</key><string>$CLONE</string>
    <key>RunAtLoad</key><true/>
    <key>KeepAlive</key><dict><key>SuccessfulExit</key><false/></dict>
    <key>StandardOutPath</key><string>$BOT_LOG</string>
    <key>StandardErrorPath</key><string>$BOT_LOG</string>
</dict>
</plist>
PLIST_XML
    cat > "$UPDATE_PLIST" <<PLIST_XML
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key><string>$UPDATE_LABEL</string>
    <key>ProgramArguments</key>
    <array>
        <string>$BOT_HOME/koi-bot.sh</string>
        <string>update</string>
    </array>
    <key>StartInterval</key><integer>3600</integer>
    <key>RunAtLoad</key><false/>
    <key>StandardOutPath</key><string>$UPDATE_LOG</string>
    <key>StandardErrorPath</key><string>$UPDATE_LOG</string>
</dict>
</plist>
PLIST_XML
    launchctl bootout "gui/$UID/$LABEL" >/dev/null 2>&1 || true
    launchctl bootout "gui/$UID/$UPDATE_LABEL" >/dev/null 2>&1 || true
    launchctl bootout "gui/$UID/$AUTOSTART_LABEL" >/dev/null 2>&1 || true
    kill_stray_bots
    cat > "$AUTOSTART_PLIST" <<PLIST_XML
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key><string>$AUTOSTART_LABEL</string>
    <key>ProgramArguments</key>
    <array>
        <string>$BOT_HOME/koi-bot.sh</string>
        <string>autostart</string>
    </array>
    <key>StartInterval</key><integer>120</integer>
    <key>RunAtLoad</key><false/>
    <key>StandardOutPath</key><string>$AUTOSTART_LOG</string>
    <key>StandardErrorPath</key><string>$AUTOSTART_LOG</string>
</dict>
</plist>
PLIST_XML
    launchctl bootstrap "gui/$UID" "$PLIST"
    launchctl bootstrap "gui/$UID" "$UPDATE_PLIST"
    launchctl bootstrap "gui/$UID" "$AUTOSTART_PLIST"
    log "launchd agents installed: start at login, restart on crash, hourly update check"
}

cmd_uninstall_launchd() {
    close_status_window
    launchctl bootout "gui/$UID/$LABEL" >/dev/null 2>&1 || true
    launchctl bootout "gui/$UID/$UPDATE_LABEL" >/dev/null 2>&1 || true
    launchctl bootout "gui/$UID/$AUTOSTART_LABEL" >/dev/null 2>&1 || true
    rm -f "$PLIST" "$UPDATE_PLIST" "$AUTOSTART_PLIST"
    log "launchd agents removed"
}

usage() {
    sed -n '2,20p' "$0" | sed 's/^# \{0,1\}//'
}

main() {
    local command="${1:-}"
    [ $# -gt 0 ] && shift
    case "$command" in
        install) cmd_install "$@" ;;
        update) cmd_update "$@" ;;
        start) cmd_start "$@" ;;
        stop) cmd_stop "$@" ;;
        restart) cmd_restart "$@" ;;
        autostart) cmd_autostart "$@" ;;
        status) cmd_status "$@" ;;
        logs) cmd_logs "$@" ;;
        run) run_foreground ;;
        install-launchd) cmd_install_launchd "$@" ;;
        uninstall-launchd) cmd_uninstall_launchd "$@" ;;
        ''|help|-h|--help) usage ;;
        *) usage; die "unknown command: $command" ;;
    esac
}

main "$@"
